# theme_id -> {label, mode, colors}
THEME_DEFINITIONS = {
    "light": {"label": "浅色", "mode": "light", "colors": _LIGHT},
    "dark": {"label": "深色", "mode": "dark", "colors": _DARK},
    "green": {"label": "绿色", "mode": "light", "colors": _GREEN},
    "orange": {"label": "橙色", "mode": "light", "colors": _ORANGE},
}

# map system/accent combinations to concrete theme ids
SYSTEM_DARK_THEME = "dark"
SYSTEM_LIGHT_THEME = "light"
ACCENT_THEMES = ("green", "orange")

# The active palette; page-level stylesheets read these tokens at runtime.
COLORS = dict(_LIGHT)
_ACTIVE_THEME_ID = "light"


def appearance_choices() -> list[tuple[str, str]]:
    """Return selectable appearance ids and labels for the settings UI."""
    return [("light", "浅色"), ("dark", "深色"), ("system", "跟随系统"),
            ("green", "绿色"), ("orange", "橙色")]


def is_dark_theme_id(theme_id: str) -> bool:
    return THEME_DEFINITIONS[theme_id]["mode"] == "dark"


def is_dark_active() -> bool:
    """Whether the currently applied theme is a dark palette."""
    return is_dark_theme_id(_ACTIVE_THEME_ID)


def theme_color(name: str) -> str:
    """Return a token from the active palette (fallback to light theme)."""
    if name in COLORS:
        return COLORS[name]
    return _LIGHT.get(name, "#172033")


def resolve_qss(qss: str) -> str:
    """Substitute ``@name@`` placeholders with the active palette values."""
    for name, value in COLORS.items():
        qss = qss.replace("@" + name + "@", value)
    return qss


def resolve_appearance(appearance: str) -> str:
    """Map a stored appearance string to an actual theme id.

    ``system`` follows the OS light/dark preference; ``green`` / ``orange`` are
    light accent themes (their dark variant is used only when following system
    while the OS is dark, to avoid blinding the user).
    """
    if appearance == "dark":
        return "dark"
    if appearance in ACCENT_THEMES:
        return appearance if not _system_dark() else f"{appearance}_dark"
    if appearance == "green_dark" or appearance == "orange_dark":
        return appearance
    if appearance == "system":
        return SYSTEM_DARK_THEME if _system_dark() else SYSTEM_LIGHT_THEME
    return "light"


def _system_dark() -> bool:
    """Detect the Windows/macOS system color scheme."""
    try:
        if os.name == "nt":
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER,
                                r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize") as key:
                value, _ = winreg.QueryValueEx(key, "AppsUseLightTheme")
            return value == 0
        if sys.platform == "darwin":
            import subprocess
            result = subprocess.run(["defaults", "read", "-g", "AppleInterfaceStyle"],
                                    capture_output=True, text=True)
            return result.returncode == 0 and "Dark" in result.stdout
        return False
    except Exception:
        return False


def apply_theme(application: QApplication, appearance: str = "light") -> None:
    """Apply the resolved theme's palette and polished Fusion widget theme."""
    global COLORS, _ACTIVE_THEME_ID
    theme_id = resolve_appearance(appearance)
    _ACTIVE_THEME_ID = theme_id if theme_id in THEME_DEFINITIONS else "light"
    if theme_id in THEME_DEFINITIONS:
        new_colors = dict(THEME_DEFINITIONS[theme_id]["colors"])
    else:
        new_colors = dict(_LIGHT)
    # Mutate the shared dict in place so modules that did
    # `from theme import COLORS` keep observing the live palette after a switch.
    COLORS.clear()
    COLORS.update(new_colors)
    application.setStyle("Fusion")
    font_family = _preferred_font_family(application)
    application.setFont(QFont(font_family, 10))
    application.setStyleSheet(_stylesheet(font_family, COLORS))


def _preferred_font_family(application: QApplication) -> str:
    """Choose an installed Chinese-capable font before Latin-only fallbacks."""
    available = set(QFontDatabase.families())
    for font_path in _candidate_font_files():
        if font_path.is_file():
            font_id = QFontDatabase.addApplicationFont(str(font_path))
            if font_id >= 0:
                available.update(QFontDatabase.applicationFontFamilies(font_id))
    for candidate in _FONT_FAMILIES:
        if candidate in available:
            return candidate
    return application.font().family()


_FONT_FAMILIES = ("Microsoft YaHei UI", "Microsoft YaHei", "PingFang SC", "Hiragino Sans GB",
                  "Noto Sans CJK SC", "Noto Sans SC", "Source Han Sans SC", "WenQuanYi Zen Hei",
                  "DengXian", "SimSun", "Segoe UI", "Helvetica Neue", "Noto Sans", "DejaVu Sans")


def _candidate_font_files() -> tuple[Path, ...]:
    """List per-platform font files that carry Simplified Chinese glyphs."""
    if os.name == "nt":
        root = Path(os.environ.get("WINDIR", r"C:\Windows")) / "Fonts"
        return tuple(root / name for name in ("msyh.ttc", "Deng.ttf", "simsun.ttc"))
    if sys.platform == "darwin":
        return (Path("/System/Library/Fonts/PingFang.ttc"),
                Path("/System/Library/Fonts/STHeiti Light.ttc"),
                Path("/Library/Fonts/Arial Unicode.ttf"))
    return (Path("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"),
            Path("/usr/share/fonts/opentype/noto/NotoSansCJKsc-Regular.otf"),
            Path("/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc"),
            Path("/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc"),
            Path("/usr/share/fonts/truetype/arphic/uming.ttc"))


